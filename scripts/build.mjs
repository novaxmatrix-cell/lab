// npm run build
// content/floors.private.json (gitignored, plaintext) →
//   docs/burj/data/floors.json            public, encrypted chain
//   supabase/seed.private.sql             gitignored, answers for the Edge Function
//   supabase/functions/_shared/*.js       copies of the shared client modules

import { readFile, writeFile, copyFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { sealChain, acceptedAnswers } from './seal.mjs';
import { findLeaks } from './check-leak.mjs';
import { TZ, OPEN_HOUR, opensAtUtc } from '../docs/burj/js/schedule.js';

const root = fileURLToPath(new URL('..', import.meta.url));
const SRC = root + 'content/floors.private.json';
const OUT = root + 'docs/burj/data/floors.json';
const SEED = root + 'supabase/seed.private.sql';
export const ITERATIONS = 600_000;

let src;
try {
  src = JSON.parse(await readFile(SRC, 'utf8'));
} catch (e) {
  console.error(`Cannot read ${SRC}: ${e.message}\nCopy content/floors.example.json to content/floors.private.json first.`);
  process.exit(1);
}

const floors = src.floors;
if (!Array.isArray(floors) || !floors.length) throw new Error('floors.private.json: "floors" must be a non-empty array');
let lastOpens = null;
floors.forEach((f, i) => {
  if (typeof f.q !== 'string' || !f.q.trim()) throw new Error(`floor ${i + 1}: missing "q"`);
  if (!Array.isArray(f.answers)) throw new Error(`floor ${i + 1}: "answers" must be an array`);
  // Undated floors are open now and must come first; dates never go backwards.
  if (f.opens !== undefined) {
    opensAtUtc(f.opens); // validates the format
    if (lastOpens && f.opens < lastOpens) throw new Error(`floor ${i + 1}: opens ${f.opens} is before floor ${i}'s ${lastOpens}`);
    lastOpens = f.opens;
  } else if (lastOpens) {
    throw new Error(`floor ${i + 1}: has no "opens" but an earlier floor does`);
  }
});

const data = await sealChain(floors, { iterations: ITERATIONS });
data.build = new Date().toISOString();
await writeFile(OUT, JSON.stringify(data) + '\n');

// Seed for the floor_answers table (see supabase/schema.sql). Never committed.
const sq = (s) => `'${s.replaceAll("'", "''")}'`;
// released_at uses Postgres's own tz data, so 06:00 Hebron is right across DST changes.
const released = (f) => (f.opens ? `timestamp '${f.opens} ${String(OPEN_HOUR).padStart(2, '0')}:00' at time zone '${TZ}'` : 'now()');
const rows = floors.map((f, i) => `  (${i + 1}, array[${acceptedAnswers(f).map(sq).join(', ')}]::text[], ${released(f)})`);
await writeFile(
  SEED,
  `-- Generated by npm run build. Contains plaintext answers: do not commit.\n` +
    `insert into public.floor_answers (floor, answers, released_at) values\n${rows.join(',\n')}\n` +
    `on conflict (floor) do update set answers = excluded.answers, released_at = excluded.released_at;\n`,
);

// Stamp the service worker with a hash of the app shell so a changed shell
// installs a fresh cache (see docs/burj/sw.js).
const SW = root + 'docs/burj/sw.js';
const sw = await readFile(SW, 'utf8');
const shell = [...sw.matchAll(/'([^']+\.(?:css|js|webmanifest|svg|png))'/g)].map((m) => m[1]).concat('index.html');
const hash = createHash('sha256');
for (const f of shell.sort()) hash.update(f).update(await readFile(root + 'docs/burj/' + f));
const version = hash.digest('hex').slice(0, 12);
await writeFile(SW, sw.replace(/const VERSION = '[^']*';/, `const VERSION = '${version}';`));

for (const f of ['normalize.js', 'badwords.js', 'towns.js']) {
  await copyFile(root + 'docs/burj/js/' + f, root + 'supabase/functions/_shared/' + f);
}

const leaks = await findLeaks(floors, src.publicWords);
if (leaks.length) {
  console.error('Plaintext answers found in public files:\n' + leaks.join('\n'));
  process.exit(1);
}

const dated = floors.filter((f) => f.opens);
console.log(`Built ${floors.length} floors → docs/burj/data/floors.json (PBKDF2 ${ITERATIONS})` + (dated.length ? `, ${dated.length} dated ${dated[0].opens} … ${dated.at(-1).opens}` : ''));
console.log('Wrote supabase/seed.private.sql (gitignored)');
console.log(`Service worker cache version ${version}`);
